/**
 * Owner's directive, 2026-11-26 ("Garanta que os 30 produtos... sejam
 * cadastrados corretamente no banco de produção", extended the same day
 * for the second campaign): the production image (see Dockerfile — a
 * Next.js "standalone" build) ships neither `tsx` nor the
 * `scripts/`/`data/` directories, only a hand-installed Prisma CLI for
 * migrations — confirmed by reading the Dockerfile's runner stage before
 * assuming scripts/import-black-friday-2026.ts could run there the way
 * it does locally. This generates the SQL equivalent of that script from
 * one campaign's own data/<campaign>-export.json, meant to run directly
 * via `docker compose exec db psql`, which needs nothing beyond what's
 * already in the `db` container.
 *
 * Usage: tsx scripts/generate-black-friday-2026-seed-sql.ts <campaign-slug>
 * (defaults to "black-friday-2026" when omitted).
 *
 * Same idempotent rule as import-black-friday-2026.ts: creatives are
 * upserted by sha256 (never clobbering groupKey/filename/path — those
 * are objective facts, always safe to refresh); products are upserted by
 * (campaign, slotNumber) — the real unique key now that a second
 * campaign also numbers its own products starting at 1 — with
 * `affiliateUrl`/`currentPrice`/`selectedCreativeId` only ever set via
 * SQL's COALESCE(existing, new) — never overwritten once the owner has
 * pasted something real — and `status`/`enabled` deliberately left OUT
 * of the UPDATE clause entirely, so a re-run never resets a product the
 * owner already validated or disabled.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

interface ExportedCreative {
  sha256: string;
  groupKey: string;
  originalFilename: string;
  storedPath: string;
}
interface ExportedProduct {
  slotNumber: number;
  creativeGroupKey: string;
  name: string;
  brand: string | null;
  advertisedPrice: number | null;
  currentPrice: number | null;
  mlUrlOriginal: string | null;
  resolvedProductUrl: string | null;
  resolvedExternalId: string | null;
  resolvedTitle: string | null;
  enabled: boolean;
  affiliateUrl: string | null;
  attributionTag: string;
  status: string;
  reviewNote: string | null;
  selectedCreativeSha256: string | null;
}

function sqlString(value: string | null): string {
  if (value === null) return "NULL";
  return `'${value.replace(/'/g, "''")}'`;
}
function sqlNumber(value: number | null): string {
  return value === null ? "NULL" : String(value);
}
function sqlBool(value: boolean): string {
  return value ? "true" : "false";
}
function cuidLike(seed: string): string {
  // Not a real cuid — Postgres has no cuid() function and cuid
  // generation in this project only ever happens in the Prisma client.
  // Any unique TEXT value satisfies the column (no length constraint on
  // this TEXT column); derived from the campaign + sha256/slotNumber so
  // re-generating this file is deterministic AND never collides between
  // two campaigns' own ids. BUG FIXED 2026-11-26: an earlier version
  // sliced this to 30 chars — for a long campaign slug like
  // "black-friday-fim-do-mundo" that ate the ENTIRE budget before the
  // hash suffix, collapsing every creative onto the identical id and
  // failing with a real primary-key collision (caught here, before
  // trusting this against production). No length cap now.
  return `bfseed_${seed}`.replace(/[^a-zA-Z0-9_]/g, "");
}

function main() {
  const campaign = process.argv[2] ?? "black-friday-2026";
  const exportPath = join(process.cwd(), "data", `${campaign}-export.json`);
  const raw = JSON.parse(readFileSync(exportPath, "utf-8")) as {
    campaign: string;
    creatives: ExportedCreative[];
    products: ExportedProduct[];
  };

  const lines: string[] = [
    `-- Generated by scripts/generate-black-friday-2026-seed-sql.ts ${campaign} from`,
    `-- data/${campaign}-export.json — do not hand-edit, regenerate instead.`,
    "BEGIN;",
    "",
  ];

  for (const c of raw.creatives) {
    const id = cuidLike(`${campaign}_${c.sha256}`);
    lines.push(
      `INSERT INTO "BlackFridayCreative" (id, campaign, "groupKey", sha256, "originalFilename", "storedPath", "importedAt")`,
      `VALUES (${sqlString(id)}, ${sqlString(campaign)}, ${sqlString(c.groupKey)}, ${sqlString(c.sha256)}, ${sqlString(c.originalFilename)}, ${sqlString(c.storedPath)}, now())`,
      `ON CONFLICT (sha256) DO UPDATE SET campaign = EXCLUDED.campaign, "groupKey" = EXCLUDED."groupKey", "originalFilename" = EXCLUDED."originalFilename", "storedPath" = EXCLUDED."storedPath";`,
      "",
    );
  }

  for (const p of raw.products) {
    const id = cuidLike(`${campaign}_slot${p.slotNumber}`);
    const selectedCreativeIdExpr = p.selectedCreativeSha256
      ? `(SELECT id FROM "BlackFridayCreative" WHERE sha256 = ${sqlString(p.selectedCreativeSha256)})`
      : "NULL";
    lines.push(
      `INSERT INTO "BlackFridayProduct" (id, campaign, "slotNumber", "creativeGroupKey", name, brand, "advertisedPrice", "currentPrice", "mlUrlOriginal", "resolvedProductUrl", "resolvedExternalId", "resolvedTitle", "resolvedAt", enabled, "affiliateUrl", "attributionTag", status, "reviewNote", "selectedCreativeId", "createdAt", "updatedAt")`,
      `VALUES (${sqlString(id)}, ${sqlString(campaign)}, ${p.slotNumber}, ${sqlString(p.creativeGroupKey)}, ${sqlString(p.name)}, ${sqlString(p.brand)}, ${sqlNumber(p.advertisedPrice)}, ${sqlNumber(p.currentPrice)}, ${sqlString(p.mlUrlOriginal)}, ${sqlString(p.resolvedProductUrl)}, ${sqlString(p.resolvedExternalId)}, ${sqlString(p.resolvedTitle)}, now(), ${sqlBool(p.enabled)}, ${sqlString(p.affiliateUrl)}, ${sqlString(p.attributionTag)}, ${sqlString(p.status)}::"BlackFridayProductStatus", ${sqlString(p.reviewNote)}, ${selectedCreativeIdExpr}, now(), now())`,
      `ON CONFLICT (campaign, "slotNumber") DO UPDATE SET`,
      `  "creativeGroupKey" = EXCLUDED."creativeGroupKey",`,
      `  name = EXCLUDED.name,`,
      `  brand = EXCLUDED.brand,`,
      `  "advertisedPrice" = EXCLUDED."advertisedPrice",`,
      `  "mlUrlOriginal" = EXCLUDED."mlUrlOriginal",`,
      `  "resolvedProductUrl" = EXCLUDED."resolvedProductUrl",`,
      `  "resolvedExternalId" = EXCLUDED."resolvedExternalId",`,
      `  "resolvedTitle" = EXCLUDED."resolvedTitle",`,
      `  "resolvedAt" = EXCLUDED."resolvedAt",`,
      `  "attributionTag" = EXCLUDED."attributionTag",`,
      `  "reviewNote" = EXCLUDED."reviewNote",`,
      `  "currentPrice" = COALESCE("BlackFridayProduct"."currentPrice", EXCLUDED."currentPrice"),`,
      `  "affiliateUrl" = COALESCE("BlackFridayProduct"."affiliateUrl", EXCLUDED."affiliateUrl"),`,
      `  "selectedCreativeId" = COALESCE("BlackFridayProduct"."selectedCreativeId", EXCLUDED."selectedCreativeId"),`,
      `  "updatedAt" = now();`,
      "",
    );
  }

  lines.push("COMMIT;", "");

  const outPath = join(process.cwd(), "data", `${campaign}-seed.sql`);
  writeFileSync(outPath, lines.join("\n"));
  console.log(`Gerado (${campaign}): ${outPath} (${raw.creatives.length} criativos, ${raw.products.length} produtos)`);
}

main();
